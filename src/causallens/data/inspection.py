"""Structural inspection only; no EDA, preprocessing or estimator fitting."""
from pathlib import Path
import numpy as np
from .acquisition import sha256
from .loader import archive_path, load_ihdp, load_ihdp_truth, validate_archive, FEATURE_NAMES


def inspect_ihdp(data_dir="data/raw", replication=0):
    result = {"replication": int(replication), "splits": {}}
    rows = {}
    for split in ("train", "test"):
        path = archive_path(split, data_dir)
        schema = validate_archive(path)
        observed = load_ihdp(replication, split, data_dir)
        truth = load_ihdp_truth(replication, split, data_dir)
        X, T, Y = (observed[k] for k in ("X", "T", "Y"))
        counts = {str(v): int((T == v).sum()) for v in (0,1)}
        columns = []
        for j, name in enumerate(FEATURE_NAMES):
            u = np.unique(X[:,j])
            columns.append({"feature": name, "min": float(u.min()), "max": float(u.max()),
                            "unique_count": len(u), "levels": u.tolist() if len(u)<=2 else None,
                            "is_zero_one": bool(np.isin(u,[0,1]).all()),
                            "missing": int(np.isnan(X[:,j]).sum())})
        # Exact covariate+assignment fingerprints are not patient IDs. Overlap
        # would merit review; absence cannot establish disjoint patient identity.
        rows[split] = {tuple(row) for row in np.column_stack([X,T])}
        result["splits"][split] = {
            "filename": path.name, "sha256": sha256(path), "bytes": path.stat().st_size,
            "schema": schema, "n": len(T), "n_features": X.shape[1],
            "treated": counts["1"], "control": counts["0"],
            "yf": {"mean": float(Y.mean()), "min": float(Y.min()), "max": float(Y.max())},
            "features": columns, "potential_outcome_shapes": {
                k:list(truth[k].shape) for k in ("mu0","mu1","ycf")},
            "sample_observed_rows": [dict(row_index=i, T=float(T[i]), Y=float(Y[i]),
                                             **{f"x{j+1:02d}":float(X[i,j]) for j in range(3)})
                                      for i in range(min(5,len(T)))],
            "yf_equals_assigned_expected_mean": bool(np.array_equal(
                Y, np.where(T==1, truth["mu1"], truth["mu0"]))),
        }
    duplicates = len(rows["train"] & rows["test"])
    result["split_check"] = {
        "exact_shared_covariate_treatment_rows": duplicates,
        "interpretation": "Fingerprints only; no patient ID is available. No row-index matching across replications.",
        "official_archives_preserved": True}
    if sum(s["n"] for s in result["splits"].values()) != 747:
        raise ValueError("Combined sample count is not 747")
    if duplicates:
        raise ValueError("Exact shared feature/assignment rows require review")
    return result


def render_report(result):
    lines = ["# IHDP initial inspection — Phase 2", "",
             "Generated by `python scripts/inspect_ihdp.py`; no EDA or preprocessing performed.",
             f"Selected replication: **{result['replication']}** (zero-based).", "",
             "## Archive contents (all 100 replications)", "",
             "| Split | Key | Shape | dtype | Nonfinite values |", "|---|---|---|---|---|"]
    for split, s in result["splits"].items():
        for key,a in s["schema"].items():
            lines.append(f"| {split} | {key} | {a['shape']} | {a['dtype']} | {a['nonfinite']} |")
    lines += ["", "Replication is the final axis: x[:, :, r], and t/yf/ycf/mu0/mu1[:, r]. Metadata fields are not assumed to be patient-level arrays.",
              "", "## Replication summary", "",
              "| Split | n | Features | Treated | Control | yf mean | yf min | yf max |",
              "|---|---|---|---|---|---|---|---|"]
    for split,s in result["splits"].items():
        y=s["yf"]
        lines.append(f"| {split} | {s['n']} | {s['n_features']} | {s['treated']} | {s['control']} | {y['mean']:.6f} | {y['min']:.6f} | {y['max']:.6f} |")
    lines += ["", "## Feature checks for selected replication", "",
              "Generic identifiers preserve the archived order. These checks establish numeric encodings, not clinical semantics.", "",
              "| Split | Feature | Min | Max | Distinct | Two-level values | Missing |", "|---|---|---|---|---|---|---|"]
    for split,s in result["splits"].items():
        for f in s["features"]:
            lines.append(f"| {split} | {f['feature']} | {f['min']:.6g} | {f['max']:.6g} | {f['unique_count']} | {f['levels']} | {f['missing']} |")
    lines += ["", "## Small sample tables", "",
              "Five observed rows per split are available in the ignored local inspection JSON and executable notebook. Row-level values are deliberately omitted from the Git-tracked report while redistribution terms remain unresolved."]
    lines += ["", "## Integrity and provenance", ""]
    for split,s in result["splits"].items():
        lines += [f"- {split}: {s['bytes']} bytes; SHA-256 `{s['sha256']}`.",
                  f"- {split} potential-outcome shapes: `{s['potential_outcome_shapes']}`; exact yf/assigned-mean equality: `{s['yf_equals_assigned_expected_mean']}` (not a required invariant)."]
    lines += ["", "Both ZIP CRC checks and full-array finite/shape/treatment checks passed. The loader returns copies with source dtypes and numeric values unchanged.",
              f"Exact shared covariate-plus-treatment rows in this replication: {result['split_check']['exact_shared_covariate_treatment_rows']}.",
              "This is a fingerprint check, not proof of patient identity separation: the release has no verified patient ID or row mapping. The original train/test files remain separate and unchanged.",
              "", "Hashes are locally recorded baselines, not publisher-authenticated hashes. Raw data and full JSON inspection stay ignored locally; this tracked report contains only aggregate checks. Standalone redistribution terms remain unresolved; no archives are committed.",
              "", "## Scope and next step", "",
              "No imputation, scaling, recoding, feature deletion, resplitting, overlap/imbalance EDA or model fitting occurred. Ground-truth arrays are accessed explicitly for schema/semantics inspection only, never to tune a model. Phase 3 requires user approval."]
    return "\n".join(lines)+"\n"
